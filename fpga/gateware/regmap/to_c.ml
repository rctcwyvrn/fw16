(* Render a register map as a C header for host/ (omni_transport and tools). *)

open Reg

let render ~major ~minor (blocks : block list) =
  let b = Buffer.create 4096 in
  let p fmt = Printf.bprintf b fmt in
  p "/* Generated by gateware/regmap — do not edit. Regenerate with `dune build @regmap --auto-promote`. */\n";
  p "#ifndef OMNI_REGS_H\n#define OMNI_REGS_H\n\n";
  p "#define OMNI_REGMAP_VERSION_MAJOR %du\n" major;
  p "#define OMNI_REGMAP_VERSION_MINOR %du\n" minor;
  List.iter
    (fun blk ->
      p "\n/* %s — %s */\n" blk.bname blk.bdoc;
      p "#define OMNI_%s_BASE 0x%04Xu\n" blk.bname blk.base;
      List.iter
        (fun r ->
          p "#define OMNI_%s 0x%04Xu /* %s: %s */\n" r.name r.offset
            (access_to_string r.access) r.doc;
          if r.reset <> 0 then p "#define OMNI_%s_RESET 0x%08Xu\n" r.name r.reset;
          List.iter
            (fun f ->
              let mask = ((1 lsl f.width) - 1) lsl f.lsb in
              p "#define OMNI_%s_%s_SHIFT %d\n" r.name f.fname f.lsb;
              p "#define OMNI_%s_%s_MASK 0x%08Xu\n" r.name f.fname mask)
            r.fields)
        blk.regs)
    blocks;
  p "\n#endif /* OMNI_REGS_H */\n";
  Buffer.contents b
;;
