(* Render a register map as the human-readable REGMAP.md. *)

open Reg

let bits f =
  if f.width = 1 then Printf.sprintf "[%d]" f.lsb
  else Printf.sprintf "[%d:%d]" (f.lsb + f.width - 1) f.lsb
;;

let render ~major ~minor (blocks : block list) =
  let b = Buffer.create 4096 in
  let p fmt = Printf.bprintf b fmt in
  p "<!-- Generated by gateware/regmap — do not edit. -->\n";
  p "# Register map v%d.%d\n\n" major minor;
  p "BAR0, XDMA AXI-Lite master. 32-bit registers, byte offsets, one 4 KiB block per subsystem.\n";
  List.iter
    (fun blk ->
      p "\n## %s — 0x%04X\n\n%s\n\n" blk.bname blk.base blk.bdoc;
      p "| Offset | Name | Access | Reset | Description |\n| --- | --- | --- | --- | --- |\n";
      List.iter
        (fun r ->
          let fields =
            String.concat ""
              (List.map
                 (fun f ->
                   Printf.sprintf "<br>`%s` %s%s%s" (bits f) f.fname
                     (if f.alias then " (alias)" else "")
                     (if f.fdoc = "" then "" else " — " ^ f.fdoc))
                 r.fields)
          in
          p "| 0x%04X | `%s` | %s | 0x%X | %s%s |\n" r.offset r.name
            (access_to_string r.access) r.reset r.doc fields)
        blk.regs)
    blocks;
  Buffer.contents b
;;
