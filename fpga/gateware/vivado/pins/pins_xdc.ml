(* pins_xdc PINPLAN.csv — print the pin XDC for fw16_fpga_top from the card's pin table.

   bay/card/fpga/pinplan.csv is the single pin table (decision 0010): the PCB owns it, this turns it
   into PACKAGE_PIN/IOSTANDARD constraints. Every net in the CSV must be mapped to a top-level port
   or listed as board-only below, so a new pin-plan row fails the build until the gateware says
   what it is. *)

(* net -> top-level port; only the P side of a GT/refclk pair is placed (Vivado infers N). *)
let port_of_net = function
  | "GT_REFCLK0_P" -> Some "sys_clk_p"
  | "PEX_RST#" -> Some "sys_rst_n"
  | "CLK100M" -> Some "clk100m"
  | "FPGA_CLKREQ_N" -> Some "clkreq_n"
  | "FPGA_TH_ALERT" -> Some "th_alert"
  | "FPGA_TH_OVERT" -> Some "th_overt"
  | "SENSE_SCL" -> Some "sense_scl"
  | "SENSE_SDA" -> Some "sense_sda"
  | "SENSE_ALERT#" -> Some "sense_alert_n"
  | "PPS_IN" -> Some "pps_in"
  | "LED_HB" -> Some "led_hb"
  | "LED_LINK" -> Some "led_link"
  | net ->
    (* GT_RX<lane>_P / GT_TX<lane>_P; not Scanf %d, which reads "0_P" as a number with a '_'. *)
    (match String.length net = 8, String.sub net 0 3, String.sub net 6 2 with
     | true, "GT_", "_P" ->
       let lane = net.[5] in
       let dir = String.sub net 3 2 in
       if lane < '0' || lane > '3'
       then None
       else if dir = "RX"
       then Some (Printf.sprintf "pci_exp_rxp[%c]" lane)
       else if dir = "TX"
       then Some (Printf.sprintf "pci_exp_txp[%c]" lane)
       else None
     | _ | (exception Invalid_argument _) -> None)
;;

(* Nets with a ball but no port: the N side of pairs, the bench clock (DNP) and the RCAL pins. *)
let board_only net =
  String.ends_with ~suffix:"_N" net && String.starts_with ~prefix:"GT_" net
  || List.mem net [ "GT_REFCLK1_P"; "MGT_RREF"; "MGT_AVTTRCAL" ]
;;

let () =
  let path =
    match Sys.argv with
    | [| _; p |] -> p
    | _ ->
      prerr_endline "usage: pins_xdc PINPLAN.csv";
      exit 2
  in
  let ic = open_in path in
  ignore (input_line ic : string);
  print_string
    "# GENERATED by gateware/vivado/pins/pins_xdc.exe from bay/card/fpga/pinplan.csv — do not edit.\n\
     # Regenerate: dune build @runtest --auto-promote (from fpga/).\n";
  let rec loop () =
    match input_line ic with
    | exception End_of_file -> ()
    | "" -> loop ()
    | line ->
      (match String.split_on_char ',' line with
       | net :: ball :: _func :: _bank :: iostd :: _ ->
         (match port_of_net net with
          | Some port ->
            Printf.printf "set_property PACKAGE_PIN %s [get_ports {%s}]\n" ball port;
            if iostd <> "GT" && iostd <> ""
            then Printf.printf "set_property IOSTANDARD %s [get_ports {%s}]\n" iostd port
          | None when board_only net -> Printf.printf "# %s (%s): board only, no port\n" net ball
          | None ->
            Printf.eprintf "pins_xdc: pinplan net %s (%s) has no port mapping\n" net ball;
            exit 1)
       | _ ->
         Printf.eprintf "pins_xdc: malformed row: %s\n" line;
         exit 1);
      loop ()
  in
  loop ();
  close_in ic
;;
