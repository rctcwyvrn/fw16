(* patterns N — print the first N beats of the counter and PRBS-31 patterns
   from the same Pattern.Make the RTL is built from, as a golden file for the
   host's pattern ports (host/include/fw16_fpga_patterns.txt). *)

open Hardcaml
open Fw16_fpga_shell
module P = Pattern.Make (Bits)

let words beat =
  List.init Pattern.words_per_beat (fun w ->
    let half k = Bits.to_unsigned_int (Bits.select beat ~high:((64 * w) + (32 * k) + 31) ~low:((64 * w) + (32 * k))) in
    Printf.sprintf "%08x%08x" (half 1) (half 0))
  |> String.concat " "
;;

let () =
  let n =
    match Sys.argv with
    | [| _; n |] -> int_of_string n
    | _ ->
      prerr_endline "usage: patterns N";
      exit 2
  in
  print_string
    "# Generated by gateware/shell/bin/patterns.exe — do not edit. Regenerate with `dune build @regmap --auto-promote`.\n\
     # <pattern> <beat> <word 0> .. <word 3>: word i is tdata[64i+63:64i] in hex, i.e. the i-th little-endian u64 of the beat.\n\
     # PRBS-31 starts from the reset seed 0x7FFFFFFF; bit 0 of word 0 is the first LFSR output bit.\n";
  for k = 0 to n - 1 do
    Printf.printf "counter %d %s\n" k (words (P.counter_beat (Bits.of_unsigned_int ~width:64 k)))
  done;
  let state = ref (Bits.of_unsigned_int ~width:Pattern.prbs_width Pattern.prbs_seed) in
  for k = 0 to n - 1 do
    let beat, next = P.prbs_beat !state in
    state := next;
    Printf.printf "prbs31 %d %s\n" k (words beat)
  done
;;
